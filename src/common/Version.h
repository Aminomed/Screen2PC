#pragma once
#ifndef SCREEN2PC_VERSION_H
#define SCREEN2PC_VERSION_H

#define SCREEN2PC_VERSION_MAJOR 1
#define SCREEN2PC_VERSION_MINOR 5
#define SCREEN2PC_VERSION_PATCH 0

#ifndef SCREEN2PC_BUILD_NUMBER
#define SCREEN2PC_BUILD_NUMBER 0
#endif

#define SCREEN2PC_STR_HELPER(x) #x
#define SCREEN2PC_STR(x) SCREEN2PC_STR_HELPER(x)
#define SCREEN2PC_WSTR_HELPER(x) L#x
#define SCREEN2PC_WSTR(x) SCREEN2PC_WSTR_HELPER(x)

#define SCREEN2PC_PASTE4_HELPER(a, b, c, d) SCREEN2PC_STR_HELPER(a##.##b##.##c##.##d)
#define SCREEN2PC_PASTE4(a, b, c, d) SCREEN2PC_PASTE4_HELPER(a, b, c, d)

#define SCREEN2PC_VERSION_RC_STR \
    SCREEN2PC_PASTE4(SCREEN2PC_VERSION_MAJOR, SCREEN2PC_VERSION_MINOR, SCREEN2PC_VERSION_PATCH, SCREEN2PC_BUILD_NUMBER)

#define SCREEN2PC_VERSION_STR \
    SCREEN2PC_STR(SCREEN2PC_VERSION_MAJOR) "." \
    SCREEN2PC_STR(SCREEN2PC_VERSION_MINOR) "." \
    SCREEN2PC_STR(SCREEN2PC_VERSION_PATCH) "." \
    SCREEN2PC_STR(SCREEN2PC_BUILD_NUMBER)

#define SCREEN2PC_VERSION_WSTR \
    SCREEN2PC_WSTR(SCREEN2PC_VERSION_MAJOR) L"." \
    SCREEN2PC_WSTR(SCREEN2PC_VERSION_MINOR) L"." \
    SCREEN2PC_WSTR(SCREEN2PC_VERSION_PATCH) L"." \
    SCREEN2PC_WSTR(SCREEN2PC_BUILD_NUMBER)

#endif // SCREEN2PC_VERSION_H
